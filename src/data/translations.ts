/**
 * Validates that all translation keys present in English (en)
 * exist across all other 9 supported Indian languages.
 */
export function validateTranslations(): {
  missingKeys: Record<string, string[]>;
  isComplete: boolean;
} {
  const enKeys = Object.keys(TRANSLATIONS.en);
  const supportedLanguages: SupportedLanguage[] = ['en', 'hi', 'mr', 'ta', 'te', 'bn', 'gu', 'kn', 'ml', 'pa'];
  const missingKeys: Record<string, string[]> = {};
  let isComplete = true;

  for (const lang of supportedLanguages) {
    if (lang === 'en') continue;
    const langDict = TRANSLATIONS[lang] || {};
    const missing = enKeys.filter((key) => !(key in langDict) || langDict[key] === undefined || langDict[key] === '');
    if (missing.length > 0) {
      missingKeys[lang] = missing;
      isComplete = false;
    }
  }

  if (!isComplete) {
    console.warn('[validateTranslations] Missing translation keys detected:', missingKeys);
  } else {
    console.info(`[validateTranslations] All 10 languages fully validated (${enKeys.length} keys each).`);
  }

  return {
    missingKeys,
    isComplete,
  };
}

// Run initial self-check at import / startup
try {
  validateTranslations();
} catch (e) {
  console.error('[validateTranslations] Error during startup check:', e);
}

/**
 * Helper to get a translation with guaranteed English fallback
 * Supports translation keys, raw English text, and dynamic templates.
 */
export function getTranslation(lang: SupportedLanguage | string, key: string, fallback?: string): string {
  if (!key && !fallback) return '';
  const selectedLang = (lang as SupportedLanguage) in TRANSLATIONS ? (lang as SupportedLanguage) : 'en';

  if (selectedLang === 'en') {
    const enDict = TRANSLATIONS.en;
    if (enDict && enDict[key]) {
      return enDict[key];
    }
    return fallback || key;
  }

  // Check language dictionary for key
  const dict = TRANSLATIONS[selectedLang];
  if (dict && dict[key]) {
    return dict[key];
  }

  // Check language dictionary for fallback if provided
  if (fallback && dict && dict[fallback]) {
    return dict[fallback];
  }

  // If Hindi is selected, use exhaustive Hindi phrases & template matcher
  if (selectedLang === 'hi') {
    if (HINDI_PHRASES[key]) {
      return HINDI_PHRASES[key];
    }
    if (fallback && HINDI_PHRASES[fallback]) {
      return HINDI_PHRASES[fallback];
    }
    const matchedKey = lookupHindiPhrase(key);
    if (matchedKey) {
      return matchedKey;
    }
    if (fallback) {
      const matchedFallback = lookupHindiPhrase(fallback);
      if (matchedFallback) {
        return matchedFallback;
      }
    }
  }

  // Fallback to English dictionary or provided string
  const enDict = TRANSLATIONS.en;
  if (enDict && enDict[key]) {
    return enDict[key];
  }
  return fallback || key;
}

