/**
 * Normalizes input string for fuzzy phrase lookup
 */
export function normalizePhraseKey(text: string): string {
  if (!text) return '';
  return text
    .trim()
    .toLowerCase()
    .replace(/[^\w\s]/g, '')
    .replace(/\s+/g, ' ');
}

// Pre-indexed lowercase map for rapid O(1) matching
const NORMALIZED_LOOKUP: Record<string, PhraseTranslations> = {};
for (const [key, val] of Object.entries(MULTILINGUAL_PHRASES)) {
  NORMALIZED_LOOKUP[normalizePhraseKey(key)] = val;
}

/**
 * Resolves a translated string for any of the 10 supported Indian languages
 */
export function lookupMultilingualPhrase(
  lang: SupportedLanguage | string,
  phrase: string
): string | null {
  if (!phrase || typeof phrase !== 'string') return null;
  const langKey = (lang || 'en').toLowerCase().slice(0, 2) as keyof PhraseTranslations;
  if (langKey === 'en') return phrase;

  // 1. Exact string match
  const exact = MULTILINGUAL_PHRASES[phrase];
  if (exact && exact[langKey]) {
    return exact[langKey];
  }

  // 2. Normalized lowercase lookup
  const normalized = normalizePhraseKey(phrase);
  const matched = NORMALIZED_LOOKUP[normalized];
  if (matched && matched[langKey]) {
    return matched[langKey];
  }

  return null;
}
